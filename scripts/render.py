"""Generate README.md, categories/*.md and vendors/*.md from data/.

Usage: python scripts/render.py            # write files
       python scripts/render.py --check    # exit 1 if README.md is out of date
"""
from __future__ import annotations

import sys
from collections import defaultdict
from datetime import date

from common import ROOT, fmt_num, load_all, skill_url

REPO = "The-Web-Scraping-Insider/awesome-web-scraping-skills"
REPO_URL = f"https://github.com/{REPO}"
SUBREDDIT = "https://www.reddit.com/r/WebScrapingInsider/"
SCRAPEOPS = "https://scrapeops.io/?utm_source=awesome-web-scraping-skills&utm_medium=github"
GENERATED = "<!-- GENERATED by scripts/render.py from data/*.yaml. Do not edit by hand. -->"


def publisher(s, vendors):
    if s.get("vendor"):
        return vendors[s["vendor"]]["name"]
    return f"@{s['author']}"


def publisher_md(s, vendors):
    if s.get("vendor"):
        v = vendors[s["vendor"]]
        return f"[{v['name']}]({v['site']})"
    return f"[@{s['author']}](https://github.com/{s['author']})"


def stats_line(s, caps_by_id):
    bits = []
    if s["stars"] is not None:
        star = f"⭐ {fmt_num(s['stars'])}"
        if s.get("catalog"):
            star += "†"
        if s.get("stars_week"):
            star += f" (+{s['stars_week']} this week)" if s["stars_week"] > 0 else ""
        bits.append(star)
    if s["installs"] is not None:
        bits.append(f"⬇ {fmt_num(s['installs'])}")
    bits.append("🆓 Free" if not s["paid_api"] else "🔑 API key")
    tags = [caps_by_id[c]["short"] for c in s["capabilities"] if c != "open-source"]
    if tags:
        bits.append(" · ".join(f"`{t}`" for t in tags))
    return " · ".join(bits)


def item(s, vendors, caps_by_id, show_publisher=True):
    by = f" by {publisher_md(s, vendors)}" if show_publisher else ""
    desc = s["description"].rstrip(".") + "."
    return f"- [**{s['name']}**]({skill_url(s)}){by} - {desc}<br><sub>{stats_line(s, caps_by_id)}</sub>"


def install_block(skills):
    cmds = []
    for s in skills:
        if s["install"] not in cmds:
            cmds.append(s["install"])
    body = "\n".join(cmds)
    return f"<details><summary>Install</summary>\n\n```bash\n{body}\n```\n\n</details>"


def anchor(text):
    import re
    a = text.strip().lower()
    a = re.sub(r"[^\w\- ]", "", a)
    return a.replace(" ", "-")


def render_readme(skills, vendors, categories, caps, picks, stats):
    caps_by_id = {c["id"]: c for c in caps}
    by_id = {s["id"]: s for s in skills}
    ranked = sorted(skills, key=lambda s: -s["score"])
    official = [s for s in skills if s["type"] != "community"]
    community = [s for s in skills if s["type"] == "community"]
    vendor_ids = sorted({s["vendor"] for s in official})
    updated = stats.get("updated") or date.today().isoformat()
    n_free = sum(1 for s in skills if not s["paid_api"])

    L = []
    w = L.append
    w(GENERATED)
    w('<div align="center">\n')
    w("# Awesome Web Scraping Skills [![Awesome](https://awesome.re/badge.svg)](https://awesome.re)\n")
    w("**A curated, auto-ranked list of [Agent Skills](https://agentskills.io) that teach Claude Code, Cursor, Codex and other AI agents to scrape the web.**\n")
    badges = [
        f"![Skills](https://img.shields.io/badge/skills-{len(skills)}-2563eb)",
        f"![Vendors](https://img.shields.io/badge/official%20vendors-{len(vendor_ids)}-16a34a)",
        f"![Free](https://img.shields.io/badge/free%20%2F%20open%20source-{n_free}-f59e0b)",
        f"![Updated](https://img.shields.io/badge/updated-{updated.replace('-', '--')}-6b7280)",
        f"[![PRs Welcome](https://img.shields.io/badge/PRs-welcome-brightgreen)]({REPO_URL}/blob/main/CONTRIBUTING.md)",
    ]
    w(" ".join(badges) + "\n")
    w(f"<sub>Stats refreshed daily · Ranked by GitHub stars + installs · Curated by <a href=\"{SUBREDDIT}\">The Web Scraping Insider</a></sub>\n")
    w("</div>\n")

    w("## Contents\n")
    toc = [
        "What are agent skills?", "Top 10", "Quick picks", "Official vendor skills",
        "Community skills", "Capability matrix", "Browse by category",
        "Related lists and directories", "Contributing", "How the ranking works",
    ]
    for t in toc:
        w(f"- [{t}](#{anchor(t)})")
    w("")

    w("## What are agent skills?\n")
    w("Agent skills are folders with a `SKILL.md` file that an AI agent loads when a task needs them. "
      "A scraping skill teaches the agent which tool or API to use, how to call it and how to handle blocks, "
      "so you can say *\"scrape this site\"* and get working results or code. "
      "Skills use an [open format](https://agentskills.io) supported by Claude Code, Claude.ai, Cursor, Codex, Gemini CLI and 40+ other agents.\n")
    w("```bash\n# Most skills install with the open skills CLI\nnpx skills add <owner/repo>\n# Claude Code plugins\n/plugin marketplace add <owner/repo>\n```\n")

    w("## Top 10\n")
    w("Ranked by score (stars, installs and recent activity; see [how the ranking works](#how-the-ranking-works)). "
      "**Vendor** skills come from companies selling a scraping product; **open source** skills come from the authors of a free tool or library; **community** skills come from independent developers.\n")
    type_label = {"official-vendor": "Vendor", "official-tool": "Open source", "community": "Community"}

    def top_table(title, items, show_type=True):
        w(f"### {title}\n")
        w("| # | Skill | Publisher |" + (" Type |" if show_type else "") + " ⭐ Stars | ⬇ Installs | Score |")
        w("|---:|---|---|" + ("---|" if show_type else "") + "---:|---:|---:|")
        for i, s in enumerate(items[:10], 1):
            star = fmt_num(s["stars"]) + ("†" if s.get("catalog") and s["stars"] is not None else "")
            typ = f" {type_label[s['type']]} |" if show_type else ""
            w(f"| {i} | [{s['name']}]({skill_url(s)}) | {publisher(s, vendors)} |{typ} {star} | {fmt_num(s['installs'])} | {s['score']} |")
        w("")

    top_table("🏆 Overall", ranked)
    top_table("🏢 From vendors", [s for s in ranked if s["type"] == "official-vendor"], show_type=False)
    top_table("👥 Open source & community", [s for s in ranked if s["type"] != "official-vendor"])
    w("<sub>† Stars belong to a multi-purpose collection repo, so they count for less in the score.</sub>\n")

    w("## Quick picks\n")
    w("| I need to… | Try |")
    w("|---|---|")
    for p in picks:
        links = ", ".join(f"[{by_id[i]['name'].split(',')[0]}]({skill_url(by_id[i])}) ({publisher(by_id[i], vendors)})" for i in p["skills"])
        w(f"| {p['need']} | {links} |")
    w("")

    w("## Official vendor skills\n")
    w("Skills published by the company or project behind the tool. Vendors are ordered by their best-ranked skill.\n")
    vendor_order = sorted(vendor_ids, key=lambda v: -max(s["score"] for s in official if s["vendor"] == v))
    for vid in vendor_order:
        v = vendors[vid]
        vs = sorted([s for s in official if s["vendor"] == vid], key=lambda s: -s["score"])
        w(f"### {v['name']}\n")
        w(f"<sub>{v['kind']} · [{v['site'].split('//')[-1].rstrip('/')}]({v['site']}) · [all {v['name']} skills](vendors/{vid}.md)</sub>\n")
        for s in vs:
            w(item(s, vendors, caps_by_id, show_publisher=False))
        w("")
        w(install_block(vs))
        w("")

    w("## Community skills\n")
    w("Skills written by independent developers, grouped by category and ordered by score.\n")
    for c in categories:
        cs = sorted([s for s in community if s["category"] == c["id"]], key=lambda s: -s["score"])
        if not cs:
            continue
        w(f"### {c['emoji']} {c['title']}\n")
        for s in cs:
            w(item(s, vendors, caps_by_id))
        w("")

    w("## Capability matrix\n")
    w("What each skill can do, as described in its `SKILL.md` or the vendor's docs.\n")
    w("<details><summary>Show the full matrix</summary>\n")
    cols = [c for c in caps if c["id"] != "sdk-guides"]
    w("| Skill | Publisher | " + " | ".join(c["short"] for c in cols) + " |")
    w("|---|---|" + "|".join(":-:" for _ in cols) + "|")
    for s in ranked:
        cells = []
        for c in cols:
            if c["id"] == "open-source":
                cells.append("✅" if not s["paid_api"] else "")
            else:
                cells.append("✅" if c["id"] in s["capabilities"] else "")
        w(f"| [{s['name'].split(',')[0]}]({skill_url(s)}) | {publisher(s, vendors)} | " + " | ".join(cells) + " |")
    w("\n" + " · ".join(f"**{c['short']}**: {c['description']}" for c in cols) + "\n")
    w("</details>\n")

    w("## Browse by category\n")
    for c in categories:
        n = sum(1 for s in skills if s["category"] == c["id"])
        if n:
            w(f"- [{c['emoji']} {c['title']}](categories/{c['id']}.md) ({n}) - {c['blurb']}")
    w("")

    w("## Related lists and directories\n")
    w("- [Awesome Web Scraping MCP Servers](https://github.com/The-Web-Scraping-Insider/awesome-web-scraping-mcp-servers) - Our companion list of MCP servers for scraping.")
    w("- [VoltAgent/awesome-agent-skills](https://github.com/VoltAgent/awesome-agent-skills) - General list of 1,000+ agent skills.")
    w("- [ComposioHQ/awesome-claude-skills](https://github.com/ComposioHQ/awesome-claude-skills) - Curated Claude skills across many domains.")
    w("- [lorien/awesome-web-scraping](https://github.com/lorien/awesome-web-scraping) - Scraping libraries, tools and APIs (not agent-specific).")
    w("- [skills.sh](https://skills.sh) - Skills directory and install counts used for ranking.")
    w(f"- [r/WebScrapingInsider]({SUBREDDIT}) - Scraping community, AMAs with the people who build these tools.")
    w("")

    w("## Contributing\n")
    w(f"Know a scraping skill that's missing? [Submit it with the form]({REPO_URL}/issues/new?template=submit-skill.yml) "
      f"or open a PR that edits [`data/skills.yaml`](data/skills.yaml). Don't edit this README; it's generated. "
      f"See [CONTRIBUTING.md](CONTRIBUTING.md).\n")
    w("**Are you listed?** Add the badge to your repo:\n")
    w(f"[![Featured in Awesome Web Scraping Skills](assets/badges/featured.svg)]({REPO_URL})\n")
    w("```markdown\n"
      f"[![Featured in Awesome Web Scraping Skills](https://raw.githubusercontent.com/{REPO}/main/assets/badges/featured.svg)]({REPO_URL})\n"
      "```\n")

    w("## How the ranking works\n")
    w("Each skill gets a score from 0 to 100: **45% GitHub stars** (log-scaled), **45% installs** from skills.sh "
      "(log-scaled) and **10% recent activity** (commits in the last 90 days). Stars of multi-purpose collection repos count for a quarter. "
      "Inclusion is editorial; ranking is automatic and identical for every vendor. "
      "Full details: [METHODOLOGY.md](METHODOLOGY.md).\n")

    w("---\n")
    w(f'<div align="center"><sub>Curated by <a href="{SUBREDDIT}">The Web Scraping Insider</a> · '
      f'Supported by <a href="{SCRAPEOPS}">ScrapeOps</a> · Stats last refreshed {updated}</sub></div>')
    return "\n".join(L) + "\n"


def render_category(c, skills, vendors, caps):
    caps_by_id = {x["id"]: x for x in caps}
    cs = sorted([s for s in skills if s["category"] == c["id"]], key=lambda s: -s["score"])
    L = [GENERATED, f"# {c['emoji']} {c['title']}\n", f"{c['blurb']}\n", "[← Back to the list](../README.md)\n"]
    for label, group in (("Official", [s for s in cs if s["type"] != "community"]),
                         ("Community", [s for s in cs if s["type"] == "community"])):
        if not group:
            continue
        L.append(f"## {label}\n")
        for s in group:
            L.append(item(s, vendors, caps_by_id))
        L.append("")
        L.append(install_block(group))
        L.append("")
    return "\n".join(L).replace("](vendors/", "](../vendors/") + "\n"


def render_vendor(vid, skills, vendors, caps, categories):
    caps_by_id = {x["id"]: x for x in caps}
    cat_title = {c["id"]: c["title"] for c in categories}
    v = vendors[vid]
    vs = sorted([s for s in skills if s.get("vendor") == vid], key=lambda s: -s["score"])
    L = [GENERATED, f"# {v['name']} agent skills\n",
         f"{v['kind']} · [{v['site']}]({v['site']})\n", "[← Back to the list](../README.md)\n",
         "| Skill | Category | ⭐ Stars | ⬇ Installs | Score |", "|---|---|---:|---:|---:|"]
    for s in vs:
        L.append(f"| [{s['name']}]({skill_url(s)}) | {cat_title[s['category']]} | {fmt_num(s['stars'])} | {fmt_num(s['installs'])} | {s['score']} |")
    L.append("")
    for s in vs:
        L.append(item(s, vendors, caps_by_id, show_publisher=False))
    L.append("")
    L.append(install_block(vs))
    return "\n".join(L) + "\n"


def main():
    skills, vendors, categories, caps, picks, stats = load_all()
    readme = render_readme(skills, vendors, categories, caps, picks, stats)
    if "--check" in sys.argv:
        current = (ROOT / "README.md").read_text(encoding="utf-8") if (ROOT / "README.md").exists() else ""
        sys.exit(0 if current == readme else 1)
    (ROOT / "README.md").write_text(readme, encoding="utf-8")
    (ROOT / "categories").mkdir(exist_ok=True)
    for c in categories:
        if any(s["category"] == c["id"] for s in skills):
            (ROOT / "categories" / f"{c['id']}.md").write_text(render_category(c, skills, vendors, caps), encoding="utf-8")
    (ROOT / "vendors").mkdir(exist_ok=True)
    for vid in {s["vendor"] for s in skills if s.get("vendor")}:
        (ROOT / "vendors" / f"{vid}.md").write_text(render_vendor(vid, skills, vendors, caps, categories), encoding="utf-8")
    print(f"Rendered README with {len(skills)} skills.")


if __name__ == "__main__":
    main()
